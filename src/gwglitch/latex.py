"""Emit LaTeX fragments so the write-up cannot drift from the analysis.

Two kinds of output:

``numbers.tex``
    ``\\renewcommand`` definitions for the inline quantities quoted in the
    text.  ``paper/main.tex`` declares each of them with ``\\providecommand``
    defaulting to a visible red placeholder, so a number that the pipeline has
    not produced is impossible to mistake for one it has.

``generated/<name>.tex``
    A complete ``tabular`` environment: column specification, rules, header and
    rows.  The caption, label and surrounding prose stay in the section file.

    It has to be the whole environment, not just the rows.  LaTeX's file
    inclusion performs look-ahead on the token after it, which misbehaves
    inside an alignment: pulling rows into the middle of a ``tabular`` fails
    with a misplaced ``noalign`` at the closing rule.  Keeping the inclusion
    outside any alignment avoids the problem entirely.  The column
    specification and header therefore come from
    ``paper/placeholders/<name>.spec``, so the generated and placeholder
    versions of a table cannot drift apart.

Nothing here writes a complete document; the paper is not machine-generated,
only its numbers are.
"""

from __future__ import annotations

import logging
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Mapping, Sequence

import numpy as np
import pandas as pd

log = logging.getLogger(__name__)

__all__ = [
    "macro_name",
    "fmt",
    "write_macros",
    "write_table_body",
]

_ROMAN = {
    "0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
    "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine",
}


def macro_name(key: str) -> str:
    """``slow_fraction_L1`` -> ``\\ResultSlowFractionLOne``.

    TeX control sequences may not contain digits or underscores, so digits are
    spelled out and separators removed.
    """
    parts = re.split(r"[^0-9A-Za-z]+", str(key))
    camel = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return "Result" + "".join(_ROMAN.get(c, c) for c in camel)


def fmt(
    value,
    precision: int = 3,
    percent: bool = False,
    scientific: bool = False,
    thousands: bool = False,
) -> str:
    """Format a number for LaTeX, or return an em dash for a missing one."""
    if value is None:
        return "---"
    try:
        x = float(value)
    except (TypeError, ValueError):
        return str(value)
    if not np.isfinite(x):
        return "---"

    if percent:
        # "%g" switches to exponent notation at three significant figures, so
        # a fraction of 1.0 at precision 2 renders as "1e+02" per cent.  Fall
        # back to a fixed representation whenever that happens.
        text = f"{100.0 * x:.{precision}g}"
        if "e" in text or "E" in text:
            text = f"{100.0 * x:.{max(precision - 2, 0)}f}"
            if "." in text:
                # Strip only the zeros that follow a decimal point; doing it
                # unconditionally turns "100" into "1".
                text = text.rstrip("0").rstrip(".")
        return rf"\SI{{{text}}}{{\percent}}"
    if scientific:
        mantissa, exponent = f"{x:.{precision}e}".split("e")
        return rf"${mantissa} \times 10^{{{int(exponent)}}}$"
    if thousands:
        return f"{int(round(x)):,}".replace(",", r"\,")
    return f"{x:.{precision}g}"


def interval(lo, hi, precision: int = 2) -> str:
    """``[lo, hi]`` as a bracketed LaTeX interval."""
    return f"$[{fmt(lo, precision)},\\, {fmt(hi, precision)}]$"


def write_macros(path: Path, values: Mapping[str, str]) -> Path:
    """Write ``\\renewcommand`` definitions for every entry in ``values``.

    Keys are plain identifiers; :func:`macro_name` turns them into control
    sequences.  ``\\renewcommand`` rather than ``\\newcommand`` because
    ``main.tex`` has already declared each one with a placeholder default --
    which means a typo in a key here produces a LaTeX error rather than a
    silently missing number.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "% Generated by gwglitch -- do not edit by hand.",
        f"% Written {datetime.now(timezone.utc).isoformat()}",
        "%",
        "% Each macro below is declared in main.tex with \\providecommand and a",
        "% visible placeholder default; this file replaces those defaults with",
        "% the measured values.  The presence of this file also removes the",
        "% status notice at the head of the results section.",
        "",
    ]
    for key, value in values.items():
        lines.append(rf"\renewcommand{{\{macro_name(key)}}}{{{value}}}")
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")
    log.info("wrote %s (%d macros)", path, len(values))
    return path


def read_spec(spec_path: Path) -> tuple[str, str]:
    """Read a ``<name>.spec`` file: column specification and header row.

    The spec lives beside the placeholder table so that the generated and
    placeholder versions of a table are guaranteed to have the same shape.
    """
    text = Path(spec_path).read_text(encoding="utf-8")
    colspec, header = text.split("@@@", 1)
    return colspec.strip(), header.strip()


def write_table_body(
    path: Path,
    df: pd.DataFrame,
    columns: Sequence[str],
    formatters: Mapping[str, Callable[[object], str]] | None = None,
    max_rows: int | None = None,
    spec_path: Path | None = None,
) -> Path:
    """Write a complete ``tabular`` environment filled with ``df``.

    The column specification and header come from ``spec_path`` (defaulting to
    ``paper/placeholders/<name>.spec``), so the generated table and the
    placeholder it replaces always have the same number of columns.  A
    mismatch would otherwise surface as an unhelpful LaTeX alignment error
    long after the run that caused it.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    formatters = dict(formatters or {})

    missing = [c for c in columns if c not in df.columns]
    if missing:
        raise KeyError(f"table body is missing columns {missing}")

    if spec_path is None:
        spec_path = path.parent.parent / "placeholders" / (path.stem + ".spec")
    colspec, header = read_spec(spec_path)

    n_cols = _count_columns(colspec)
    if n_cols != len(columns):
        raise ValueError(
            f"{path.name}: the column specification {colspec!r} has {n_cols} "
            f"columns but {len(columns)} were supplied"
        )

    frame = df if max_rows is None else df.head(max_rows)

    lines = [
        "% Generated by gwglitch -- do not edit by hand.",
        r"\begin{tabular}{" + colspec + "}",
        r"\toprule",
        header,
        r"\midrule",
    ]
    for record in frame.itertuples(index=False):
        values = dict(zip(frame.columns, record))
        cells = [
            formatters.get(col, lambda v: fmt(v))(values[col])
            for col in columns
        ]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("wrote %s (%d rows)", path.name, len(frame))
    return path


def _count_columns(colspec: str) -> int:
    """Number of columns in a LaTeX column specification.

    Handles the ``l r c`` letters, ``p{..}``/``m{..}``/``b{..}`` with their
    braced width, and ``>{..}``/``<{..}`` decorations, which do not themselves
    introduce a column.
    """
    count = 0
    i = 0
    while i < len(colspec):
        c = colspec[i]
        if c in "lrc":
            count += 1
            i += 1
        elif c in "pmb" and i + 1 < len(colspec) and colspec[i + 1] == "{":
            count += 1
            i = _skip_braces(colspec, i + 1)
        elif c in "><@!" and i + 1 < len(colspec) and colspec[i + 1] == "{":
            i = _skip_braces(colspec, i + 1)
        else:
            i += 1
    return count


def _skip_braces(text: str, start: int) -> int:
    depth, i = 0, start
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return i


def escape(text: str) -> str:
    """Escape the characters that break LaTeX in a channel name or label."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
        "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    out = str(text)
    for old, new in replacements.items():
        out = out.replace(old, new)
    return out


def code(text: str) -> str:
    """Wrap an identifier in the document's ``\\code`` macro, escaped."""
    return rf"\code{{{escape(text)}}}"
